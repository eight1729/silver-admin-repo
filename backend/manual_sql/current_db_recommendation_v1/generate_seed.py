"""Offline SQL renderer; imports no application settings and never connects to a DB."""
from pathlib import Path
from datetime import date
from uuid import UUID, uuid5
import argparse

ROOT = Path(__file__).resolve().parent
NAMESPACE = UUID('2844f083-9685-55ab-a141-01b34f7a5537')


def members():
    # Fictional dates: ages 60..80 at fixed 2026-12-31, never dependent on today.
    return [(str(uuid5(NAMESPACE, f'sumida/member/{n}')), str(n),
             f'CURRENT-DB-REC-V1 MEMBER {n:03}', n - 30,
             date(1946 + (n - 31) % 21, 1 + (n - 31) % 12, 1 + (n - 31) % 28).isoformat()) for n in range(31, 121)]


def jobs():
    return [(str(uuid5(NAMESPACE, f'sumida/job/{j}')), f'REC-V1-JOB-{j:03}',
             f'CURRENT-DB-REC-V1 JOB {j:03}', j * 7) for j in range(1, 4)]


def ratings():
    return [(str(n), f'REC-V1-JOB-{j:03}',
             (5 if n >= 71 else 1 + (n - 1) % 4) if j == 1 else 1 + (n + j) % 5)
            for j in range(1, 4) for n in range(1, 121)]


def values(rows):
    def literal(value):
        return str(value) if isinstance(value, int) else "'" + value.replace("'", "''") + "'"
    return ',\n'.join('(' + ', '.join(literal(v) for v in row) + ')' for row in rows)


def render():
    result = (ROOT / 'seed.sql.in').read_text(encoding='utf-8')
    for key, rows in [('MEMBERS', members()), ('JOBS', jobs()), ('RATINGS', ratings())]:
        result = result.replace('{{' + key + '}}', values(rows))
    return '-- GENERATED by generate_seed.py. Do not edit by hand.\n' + result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / '02_seed.sql'
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != render():
            raise SystemExit('02_seed.sql is stale; run generate_seed.py offline')
    else:
        path.write_text(render(), encoding='utf-8', newline='\n')
